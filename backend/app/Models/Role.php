<?php

namespace App\Models;

use Spatie\Permission\Models\Role as SpatieRole;

class Role extends SpatieRole
{
    /**
     * Mass assignable attributes.
     */
    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | Role
        |--------------------------------------------------------------------------
        */

        'name',

        'guard_name',

        /*
        |--------------------------------------------------------------------------
        | Tenant
        |--------------------------------------------------------------------------
        */

        'tenant_id',

        /*
        |--------------------------------------------------------------------------
        | System
        |--------------------------------------------------------------------------
        */

        'is_system',

        'is_active',

        /*
        |--------------------------------------------------------------------------
        | Metadata
        |--------------------------------------------------------------------------
        */

        'description',

    ];

    /**
     * Attribute casting.
     */
    protected $casts = [

        'is_system' => 'boolean',

        'is_active' => 'boolean',

    ];
}