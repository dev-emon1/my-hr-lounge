<?php

namespace App\DTOs\Package;

final readonly class PackageBuilderData
{
    public function __construct(

        /*
        |--------------------------------------------------------------------------
        | Basic Information
        |--------------------------------------------------------------------------
        */

        public string $name,

        public ?string $slug,

        public ?string $description,

        /*
        |--------------------------------------------------------------------------
        | Pricing
        |--------------------------------------------------------------------------
        */

        public float $priceMonthly,

        public float $priceYearly,

        /*
        |--------------------------------------------------------------------------
        | Package Configuration
        |--------------------------------------------------------------------------
        */

        public array $modules,

        public array $limits,

        public array $integrations,

        /*
        |--------------------------------------------------------------------------
        | Trial
        |--------------------------------------------------------------------------
        */

        public bool $isTrial,

        public ?int $trialPeriod,

        /*
        |--------------------------------------------------------------------------
        | Status
        |--------------------------------------------------------------------------
        */

        public string $status,

    ) {}

    /*
    |--------------------------------------------------------------------------
    | Factory
    |--------------------------------------------------------------------------
    */

    public static function fromArray(
        array $data
    ): self {

        return new self(

            /*
            |--------------------------------------------------------------------------
            | Basic
            |--------------------------------------------------------------------------
            */

            name: $data['name'],

            slug: $data['slug'] ?? null,

            description: $data['description'] ?? null,

            /*
            |--------------------------------------------------------------------------
            | Pricing
            |--------------------------------------------------------------------------
            */

            priceMonthly: (float) ($data['price_monthly'] ?? 0),

            priceYearly: (float) ($data['price_yearly'] ?? 0),

            /*
            |--------------------------------------------------------------------------
            | Package Configuration
            |--------------------------------------------------------------------------
            */

            modules: $data['modules'] ?? [],

            limits: $data['limits'] ?? [],

            integrations: $data['integrations'] ?? [],

            /*
            |--------------------------------------------------------------------------
            | Trial
            |--------------------------------------------------------------------------
            */

            isTrial: (bool) ($data['is_trial'] ?? false),

            trialPeriod: isset($data['trial_period'])
    ? (int) $data['trial_period']
    : null,

            /*
            |--------------------------------------------------------------------------
            | Status
            |--------------------------------------------------------------------------
            */

            status: $data['status'] ?? 'draft',

        );
    }
}